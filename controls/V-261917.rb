control 'V-261917' do
  title 'PostgreSQL must use centralized management of the content captured in audit records generated by all components of PostgreSQL.'
  desc 'check', <<~EOT
    On Unix systems, PostgreSQL can be configured to use stderr, csvlog, and syslog. To send logs to a centralized location, syslog should be used.

    As the database owner (shown here as "postgres"), ensure PostgreSQL uses syslog by running the following SQL:

    $ sudo su - postgres
    $ psql -c "SHOW log_destination"

    As the database owner (shown here as "postgres"), check to which log facility PostgreSQL is configured by running the following SQL:

    $ sudo su - postgres
    $ psql -c "SHOW syslog_facility"

    Check with the organization to refer to how syslog facilities are defined in their organization.

    If PostgreSQL audit records are not written directly to or systematically transferred to a centralized log management system, this is a finding.
  EOT
  desc 'fix', <<~EOT
    Note: The following instructions use the PGDATA and PGVER environment variables. Refer to APPENDIX-F for instructions on configuring PGDATA and APPENDIX-H for PGVER. 

    To ensure logging is enabled, review supplementary content APPENDIX-C for instructions on enabling logging.

    With logging enabled, as the database owner (shown here as "postgres"), configure the following parameters in postgresql.conf:

    Note: Consult the organization on how syslog facilities are defined in the syslog daemon configuration.

    $ sudo su - postgres
    $ vi ${PGDATA?}/postgresql.conf
    log_destination = 'syslog'
    syslog_facility = 'LOCAL0'
    syslog_ident = 'postgres'

    As the system administrator, reload the server with the new configuration:

    $ sudo systemctl reload postgresql-${PGVER?}
  EOT
  impact 0.5
  tag severity: 'medium'
  tag gtitle: 'SRG-APP-000356-DB-000314'
  tag gid: 'V-261917'
  tag rid: 'SV-261917r1000962_rule'
  tag stig_id: 'CD16-00-007000'
  tag cci: ["CCI-001844"]
  # CCI-001844 has no NIST SP 800-53 Rev 5 mapping in the DISA CCI list (2025-01-23); Rev 4 reference used.
  tag nist: ["AU-3 (2)"]
  aws_ready = command('aws').exist?
  only_if('The AWS CLI must be installed and configured with credentials, and the aws_db_instance_identifier input must be set, to evaluate this control.') do
    aws_ready && !input('aws_db_instance_identifier').empty?
  end

  region_flag = input('aws_region').empty? ? '' : "--region #{input('aws_region')}"
  profile_flag = input('aws_cli_profile').empty? ? '' : "--profile #{input('aws_cli_profile')}"

  describe command("aws rds describe-db-instances --db-instance-identifier #{input('aws_db_instance_identifier')} #{region_flag} #{profile_flag} --query 'DBInstances[0].EnabledCloudwatchLogsExports' --output text") do
    its('stdout') { should match(/postgresql/) }
    its('exit_status') { should eq 0 }
  end
end
